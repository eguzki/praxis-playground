#!/usr/bin/env bash
#
# BASIC build - the already-released Praxis AI gateway.
#
# This does NOT compile anything: it pulls the published, prebuilt image at a
# pinned tag and selects the minimal basic.yaml runtime config (only filters
# present in the release; no rate limiting).
#
# Usage:
#   ./build/build-basic.sh            # pull pinned tag below
#   AI_IMAGE=ghcr.io/praxis-proxy/ai:0.9 ./build/build-basic.sh
#
set -euo pipefail

cd "$(dirname "$0")/.."   # repo root

# --- Pinned release (bump this tag to move to a newer release) ---
AI_IMAGE="${AI_IMAGE:-ghcr.io/praxis-proxy/ai:0.9}"
LOCAL_IMAGE="praxis-gateway:basic"

echo "==> BASIC build: pulling released image ${AI_IMAGE}"
docker pull "${AI_IMAGE}"
docker tag "${AI_IMAGE}" "${LOCAL_IMAGE}"

echo "==> Selecting runtime config (writing .env)"
cat > .env <<EOF
# Generated by build/build-basic.sh - DO NOT EDIT BY HAND.
# Re-run ./build/build-basic.sh to regenerate.
#
# BASIC build: released, prebuilt gateway running a minimal proxy config
# (only filters present in the released image; token rate limiting is gated out).
GATEWAY_IMAGE=${LOCAL_IMAGE}
PRAXIS_CONFIG=basic.yaml
# basic.yaml has no policy document; mount the same file as a harmless
# placeholder so the compose bind mount always resolves.
PRAXIS_POLICY_CONFIG_PATH=./config/praxis/basic.yaml
RUST_LOG=info
INFERENCE_SIM_VERSION=v0.1.1
MOCKSERVER_VERSION=8.0.0
EOF

echo "==> Done."
echo "    Image:  ${LOCAL_IMAGE}  (from ${AI_IMAGE})"
echo "    Config: basic.yaml (minimal proxy; token rate limiting not in this release)"
echo "    Next:   make deploy-gateway && make test"
